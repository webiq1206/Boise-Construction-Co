/**
 * Rewrites shared/content/pillars/index.ts from whatever pillar files are on disk.
 *
 * Same reasoning as the wave2 barrel: a pillar that exists on disk but is not
 * imported here simply does not appear on the site, and nothing fails.
 *
 * Run: node scripts/generate-pillar-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';

const DIR = path.join(process.cwd(), 'shared', 'content', 'pillars');

const files = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .sort();

const pillars = files.map((file) => {
  const src = readFileSync(path.join(DIR, file), 'utf8');
  const exportMatch = src.match(/export const (\w+)\s*:\s*GuidePageData/);
  if (!exportMatch) throw new Error(`${file}: no "export const X: GuidePageData" found`);
  const slugMatch = src.match(/slug:\s*'([^']+)'/);
  if (!slugMatch) throw new Error(`${file}: no slug found`);
  const expectedSlug = file.replace(/\.ts$/, '');
  if (slugMatch[1] !== expectedSlug) {
    throw new Error(`${file}: slug "${slugMatch[1]}" does not match its filename`);
  }
  return { file: expectedSlug, name: exportMatch[1] };
});

const imports = pillars.map((p) => `import { ${p.name} } from './${p.file}';`).join('\n');
const entries = pillars.map((p) => `  ${p.name},`).join('\n');

const out = `/**
 * Generated by scripts/generate-pillar-index.mjs. Do not edit by hand.
 *
 * One hub pillar guide per file. ${pillars.length} pillars.
 */
import type { GuidePageData } from '../../guideContent';
${imports}

export const PILLAR_GUIDES: GuidePageData[] = [
${entries}
];
`;

writeFileSync(path.join(DIR, 'index.ts'), out);
console.log(`Wrote pillars/index.ts with ${pillars.length} pillars.`);

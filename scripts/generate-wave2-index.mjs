/**
 * Rewrites shared/content/wave2/index.ts from whatever post files are on disk.
 *
 * The barrel is generated rather than hand-maintained because a missing import
 * here is invisible: the post file exists, the build passes, and the article
 * simply never appears on the site. Regenerate after adding or retiring a post.
 *
 * Run: node scripts/generate-wave2-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';

const DIR = path.join(process.cwd(), 'shared', 'content', 'wave2');

const files = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .sort();

const posts = files.map((file) => {
  const src = readFileSync(path.join(DIR, file), 'utf8');
  const exportMatch = src.match(/export const (\w+)\s*:\s*BlogPostData/);
  if (!exportMatch) throw new Error(`${file}: no "export const X: BlogPostData" found`);
  const slugMatch = src.match(/slug:\s*'([^']+)'/);
  if (!slugMatch) throw new Error(`${file}: no slug found`);
  const expectedSlug = file.replace(/\.ts$/, '');
  if (slugMatch[1] !== expectedSlug) {
    throw new Error(`${file}: slug "${slugMatch[1]}" does not match its filename`);
  }
  return { file: expectedSlug, name: exportMatch[1] };
});

const imports = posts.map((p) => `import { ${p.name} } from './${p.file}';`).join('\n');
const entries = posts.map((p) => `  ${p.name},`).join('\n');

const out = `/**
 * Generated by scripts/generate-wave2-index.mjs. Do not edit by hand.
 *
 * Every hand-authored article lives in its own file in this directory and is
 * collected here. ${posts.length} posts.
 */
import type { BlogPostData } from '../../blogContent';
${imports}

export const WAVE2_POSTS: BlogPostData[] = [
${entries}
];
`;

writeFileSync(path.join(DIR, 'index.ts'), out);
console.log(`Wrote wave2/index.ts with ${posts.length} posts.`);
